package com.mycompany.wisebooks.dto;

/**
 * Datos que llegan del formulario de registro (CrearCuenta.jsp). Todo llega
 * como texto; el service lo valida y lo convierte. No tiene campo "rol" a
 * proposito: el registro publico siempre crea un lector.
 */
public class RegistroDTO {

    private String nombre;
    private String apellidos;
    private String tipoDocumento;   // "CC", "TI", "CE" o "PA"
    private String documento;
    private String telefono;
    private String correo;
    private String contrasena;      // texto plano: solo vive hasta que se encripta
    private boolean aceptaTerminos;

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getApellidos() {
        return apellidos;
    }

    public void setApellidos(String apellidos) {
        this.apellidos = apellidos;
    }

    public String getTipoDocumento() {
        return tipoDocumento;
    }

    public void setTipoDocumento(String tipoDocumento) {
        this.tipoDocumento = tipoDocumento;
    }

    public String getDocumento() {
        return documento;
    }

    public void setDocumento(String documento) {
        this.documento = documento;
    }

    public String getTelefono() {
        return telefono;
    }

    public void setTelefono(String telefono) {
        this.telefono = telefono;
    }

    public String getCorreo() {
        return correo;
    }

    public void setCorreo(String correo) {
        this.correo = correo;
    }

    public String getContrasena() {
        return contrasena;
    }

    public void setContrasena(String contrasena) {
        this.contrasena = contrasena;
    }

    public boolean isAceptaTerminos() {
        return aceptaTerminos;
    }

    public void setAceptaTerminos(boolean aceptaTerminos) {
        this.aceptaTerminos = aceptaTerminos;
    }
}
