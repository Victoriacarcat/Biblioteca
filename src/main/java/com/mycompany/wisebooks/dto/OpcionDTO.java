package com.mycompany.wisebooks.dto;

/*
 * Par id + nombre, para llenar listas desplegables (categorias, generos...).
 */
public class OpcionDTO {

    private final Long id;
    private final String nombre;

    public OpcionDTO(Long id, String nombre) {
        this.id = id;
        this.nombre = nombre;
    }

    public Long getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }
}
